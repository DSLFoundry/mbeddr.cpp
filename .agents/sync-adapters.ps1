param([switch]$Write)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$marker = '<!-- Generated by .agents/sync-adapters.ps1; edit canonical instructions instead. -->'
$files = @(
    Get-ChildItem (Join-Path $PSScriptRoot 'agents') -Filter '*.agent.md'
    Get-ChildItem (Join-Path $PSScriptRoot 'skills') -Directory |
        ForEach-Object { Get-Item (Join-Path $_.FullName 'SKILL.md') }
)
$count = 0
foreach ($file in $files) {
    $canonicalText = [IO.File]::ReadAllText($file.FullName)
    if ($canonicalText -notmatch '(?s)\A---\r?\n(?<header>.*?)\r?\n---\r?\n') {
        throw "Missing canonical frontmatter: $($file.FullName)"
    }
    $header = $Matches.header
    if ($header -notmatch '(?m)^name: (?<name>[a-z0-9]+(?:-[a-z0-9]+)*)\r?$') {
        throw "Invalid canonical name: $($file.FullName)"
    }
    $name = $Matches.name
    if ($header -notmatch '(?m)^description: (?<description>[^\r\n]+)\r?$') {
        throw "Missing canonical description: $($file.FullName)"
    }
    $description = $Matches.description
    $canonical = [IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/')
    $isRole = $file.Name -ne 'SKILL.md'
    foreach ($client in '.github', '.claude') {
        $relative = if ($isRole) {
            "$client\agents\$name" + $(if ($client -eq '.github') { '.agent.md' } else { '.md' })
        } else {
            "$client\skills\$name\SKILL.md"
        }
        $path = Join-Path $root $relative
        $body = @(
            '---'
            "name: $name"
            "description: $description"
            '---'
            ''
            $marker
            ''
            "Read ``AGENTS.md``, ``.agents/PROFILE.md`` and ``$canonical`` before acting."
            'If a canonical file is unavailable, report the blocker rather than improvising.'
            'The canonical file owns scope, workflow and verified self-learning.'
            'Follow `.agents/SELF-LEARNING.md`; write verified lessons to canonical `.agents` files, never this adapter.'
            'This pointer grants no additional tool, delegation or execution permissions.'
            ''
        ) -join "`n"
        $exists = Test-Path -LiteralPath $path
        $current = if ($exists) { [IO.File]::ReadAllText($path) } else { '' }
        if ($exists -and -not $current.Contains($marker)) {
            throw "Refusing to replace an unowned adapter: $relative"
        }
        if ($current.Replace("`r`n", "`n") -ne $body) {
            if (-not $Write) { throw "Missing/stale adapter: $relative; rerun with -Write after review." }
            New-Item -ItemType Directory -Path (Split-Path $path) -Force | Out-Null
            [IO.File]::WriteAllText($path, $body, [Text.UTF8Encoding]::new($false))
        }
        $count++
    }
}
Write-Output "PASS: $count canonical discovery adapters $(if ($Write) { 'synchronized' } else { 'verified' })."
